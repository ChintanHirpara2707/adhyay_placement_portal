import { Platform } from 'react-native';
import { C } from '@/theme/design';

export interface CvData {
  full_name: string;
  email?: string | null;
  phone?: string | null;
  branch?: string | null;
  cgpa?: number | string | null;
  backlog_count?: number | null;
  skills?: string[] | null;
}

const esc = (v: unknown) =>
  String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

/** One-page A4 CV built from the student's profile. Self-contained HTML (inline CSS only). */
export function buildCvHtml(d: CvData): string {
  const skills = (d.skills ?? []).filter(Boolean);
  const contact = [d.email, d.phone].filter(Boolean).map(esc).join(' &nbsp;•&nbsp; ');
  const row = (label: string, value: unknown) =>
    value === null || value === undefined || value === '' ? '' : `<tr><td class="k">${esc(label)}</td><td>${esc(value)}</td></tr>`;

  return `<!doctype html>
<html><head><meta charset="utf-8"><title>${esc(d.full_name || 'CV')}</title>
<style>
  @page { size: A4; margin: 14mm; }
  * { box-sizing: border-box; }
  body { font-family: -apple-system, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; color: ${C.ink}; margin: 0; font-size: 12.5px; line-height: 1.5; }
  .head { border-bottom: 3px solid ${C.accent}; padding-bottom: 10px; margin-bottom: 18px; }
  h1 { font-size: 26px; margin: 0 0 4px; letter-spacing: -0.5px; }
  .contact { color: ${C.muted}; font-size: 12px; }
  h2 { font-size: 11px; letter-spacing: 1px; text-transform: uppercase; color: ${C.accent}; margin: 18px 0 8px; border-bottom: 1px solid ${C.line}; padding-bottom: 4px; }
  table { border-collapse: collapse; width: 100%; }
  td { padding: 4px 0; vertical-align: top; }
  td.k { width: 160px; color: ${C.muted}; }
  .skills span { display: inline-block; background: ${C.accentSoft}; color: ${C.accentStrong}; border-radius: 6px; padding: 3px 9px; margin: 0 6px 6px 0; font-size: 11.5px; }
  .foot { margin-top: 24px; color: ${C.faint}; font-size: 10px; }
</style></head>
<body>
  <div class="head">
    <h1>${esc(d.full_name || 'Candidate')}</h1>
    <div class="contact">${contact || '&nbsp;'}</div>
  </div>
  <h2>Academic profile</h2>
  <table>
    ${row('Department', d.branch)}
    ${row('CGPA', d.cgpa)}
    ${row('Active backlogs', d.backlog_count)}
  </table>
  <h2>Technical skills</h2>
  ${skills.length ? `<div class="skills">${skills.map((s) => `<span>${esc(s)}</span>`).join('')}</div>` : '<div class="contact">No skills added.</div>'}
  <div class="foot">Generated by Adhyay Placement Portal on ${esc(new Date().toLocaleDateString())}</div>
</body></html>`;
}

/**
 * Web: prints the CV in a hidden iframe with window.print() (the browser's "Save as PDF").
 * Native: renders a PDF with expo-print and opens the share sheet with expo-sharing.
 * Throws on failure so the caller can showAlert.
 */
export async function downloadCv(data: CvData): Promise<void> {
  const html = buildCvHtml(data);

  if (Platform.OS === 'web') {
    const frame = document.createElement('iframe');
    frame.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0;';
    document.body.appendChild(frame);
    const doc = frame.contentWindow?.document;
    if (!doc || !frame.contentWindow) {
      frame.remove();
      throw new Error('Could not open the print dialog in this browser.');
    }
    doc.open();
    doc.write(html);
    doc.close();
    // Give the iframe a tick to lay out before printing; clean up once the dialog is dismissed.
    setTimeout(() => {
      frame.contentWindow?.focus();
      frame.contentWindow?.print();
      setTimeout(() => frame.remove(), 1000);
    }, 250);
    return;
  }

  const Print = await import('expo-print');
  const Sharing = await import('expo-sharing');
  const { uri } = await Print.printToFileAsync({ html });
  if (!(await Sharing.isAvailableAsync())) throw new Error('Sharing is not available on this device.');
  await Sharing.shareAsync(uri, { mimeType: 'application/pdf', dialogTitle: 'Save or share your CV', UTI: 'com.adobe.pdf' });
}
